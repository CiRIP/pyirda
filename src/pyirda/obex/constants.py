from enum import IntEnum

VERSION = 0x10
FINAL = 0x80
MIN_PACKET_LENGTH = 255
DEFAULT_MAX_PACKET_LENGTH = 1024


class Opcode(IntEnum):
    CONNECT = 0x00
    DISCONNECT = 0x01
    PUT = 0x02
    GET = 0x03
    SETPATH = 0x05
    SESSION = 0x07
    ABORT = 0x7F


class Response(IntEnum):
    CONTINUE = 0x10
    SUCCESS = 0x20
    CREATED = 0x21
    ACCEPTED = 0x22
    NON_AUTHORITATIVE = 0x23
    NO_CONTENT = 0x24
    RESET_CONTENT = 0x25
    PARTIAL_CONTENT = 0x26
    MULTIPLE_CHOICES = 0x30
    MOVED_PERMANENTLY = 0x31
    MOVED_TEMPORARILY = 0x32
    SEE_OTHER = 0x33
    NOT_MODIFIED = 0x34
    USE_PROXY = 0x35
    BAD_REQUEST = 0x40
    UNAUTHORIZED = 0x41
    PAYMENT_REQUIRED = 0x42
    FORBIDDEN = 0x43
    NOT_FOUND = 0x44
    METHOD_NOT_ALLOWED = 0x45
    NOT_ACCEPTABLE = 0x46
    PROXY_AUTHENTICATION_REQUIRED = 0x47
    REQUEST_TIMEOUT = 0x48
    CONFLICT = 0x49
    GONE = 0x4A
    LENGTH_REQUIRED = 0x4B
    PRECONDITION_FAILED = 0x4C
    ENTITY_TOO_LARGE = 0x4D
    URL_TOO_LARGE = 0x4E
    UNSUPPORTED_MEDIA_TYPE = 0x4F
    INTERNAL_SERVER_ERROR = 0x50
    NOT_IMPLEMENTED = 0x51
    BAD_GATEWAY = 0x52
