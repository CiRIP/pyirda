    TYPE = 0x42
    LENGTH = 0xC3
    TIME = 0x44
    TIME_4BYTE = 0xC4
    DESCRIPTION = 0x05
    TARGET = 0x46
    HTTP = 0x47
    BODY = 0x48
    END_OF_BODY = 0x49
    WHO = 0x4A
    CONNECTION_ID = 0xCB
    APP_PARAMETERS = 0x4C
    AUTH_CHALLENGE = 0x4D
    AUTH_RESPONSE = 0x4E
    CREATOR_ID = 0xCF
    WAN_UUID = 0x50
    OBJECT_CLASS = 0x51
    SESSION_PARAMETERS = 0x52
